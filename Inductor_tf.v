// Description: 
//   Co-simulation cascaded path: Inverter -> Inductor -> Clarke -> Park -> Te_calc -> Mechanical.
//   Includes real-time Back-EMF calculation and dynamic Neutral Point Voltage (U_N) calculation.
//   Closed-loop configurations: Mechanical ePOS fed back to Park & BackEMF; U_N fed back to Inductor.
//   Mechanical eOMG fed back to BackEMF.
//
// Dependencies: Inductor.v, Clarke3Phase.v, Park2dq.v, Te_calc.v, Mechanical.v, BackEMF.v, 
//               add3over3.v, Volt_N_calc.v, inv_phi3_HB.v
//               (Requires associated .xco IP cores for multipliers and CORDIC)
// 
// Revision:
// Revision 1.08 - Removed the RTL SPWM_Gen from this testbench.  The testbench
// now generates a behavioral 5 kHz three-phase SPWM gate set (120 degree phase
// displacement) and feeds BackEMF outputs directly into Inductor.
// Additional Comments: All comments in coding procedure outputted in English
// 
