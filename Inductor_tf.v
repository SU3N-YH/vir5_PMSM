module Inductor_tf;

    // Clock and Reset
    reg clk_180MHz;
    reg rst_n;
    
    // Inverter gate signals generated by the behavioral testbench SPWM.
    reg S1, S2, S3, S4, S5, S6;

    // Behavioral SPWM parameters.  The fixed electrical frequency is
    // intentional: it decouples the power-stage test from the mechanical
    // startup transient.  Change this value for another operating point.
    localparam integer TB_PWM_CARRIER_HZ = 5000;
    localparam integer TB_ELECTRICAL_HZ  = 100;
    localparam integer TB_TRI_PRD        = 18000;
    localparam integer TB_DEADTIME       = 360;       // 2 us at 180 MHz
    localparam real    TB_PI             = 3.14159265358979323846;
    localparam real    TB_PHASE_STEP_DEG =
                         360.0 * TB_ELECTRICAL_HZ / TB_PWM_CARRIER_HZ;

    reg [14:0] tb_tri_cnt;
    reg        tb_tri_dir;
    real       tb_phase_deg;
    integer    tb_cmp_a, tb_cmp_b, tb_cmp_c;
    wire       tb_raw_a = (tb_tri_cnt <= tb_cmp_a);
    wire       tb_raw_b = (tb_tri_cnt <= tb_cmp_b);
    wire       tb_raw_c = (tb_tri_cnt <= tb_cmp_c);
    reg [11:0] tb_dt_a, tb_dt_b, tb_dt_c;
    reg        tb_pending_a, tb_pending_b, tb_pending_c;

    // 5 kHz up/down carrier and fixed electrical phase accumulator.  The
    // three sine values are sampled at the carrier boundary, so the compare
    // values stay coherent for the complete center-aligned PWM period.
    always @(posedge clk_180MHz or negedge rst_n) begin
        if (!rst_n) begin
            tb_tri_cnt  <= 15'd0;
            tb_tri_dir  <= 1'b0;
            tb_phase_deg = 180.0;
            tb_cmp_a = 9000;
            tb_cmp_b = 16014;
            tb_cmp_c = 1985;
        end else begin
            if (!tb_tri_dir) begin
                if (tb_tri_cnt >= TB_TRI_PRD - 1) begin
                    tb_tri_cnt <= TB_TRI_PRD;
                    tb_tri_dir <= 1'b1;
                end else begin
                    tb_tri_cnt <= tb_tri_cnt + 1'b1;
                end
            end else begin
                if (tb_tri_cnt <= 1) begin
                    tb_tri_cnt <= 15'd0;
                    tb_tri_dir <= 1'b0;
                end else begin
                    tb_tri_cnt <= tb_tri_cnt - 1'b1;
                end
            end

            if ((tb_tri_cnt == 0) && !tb_tri_dir) begin
                tb_phase_deg = tb_phase_deg + TB_PHASE_STEP_DEG;
                if (tb_phase_deg >= 360.0)
                    tb_phase_deg = tb_phase_deg - 360.0;
                tb_cmp_a = $rtoi((0.5 + 0.45 *
                           $sin(tb_phase_deg * TB_PI / 180.0)) * TB_TRI_PRD);
                tb_cmp_b = $rtoi((0.5 + 0.45 *
                           $sin((tb_phase_deg - 120.0) * TB_PI / 180.0)) * TB_TRI_PRD);
                tb_cmp_c = $rtoi((0.5 + 0.45 *
                           $sin((tb_phase_deg + 120.0) * TB_PI / 180.0)) * TB_TRI_PRD);
            end
        end
    end

    // Complementary gate generation with a 2 us blanking interval on every
    // commutation.  This models the gate timing expected by inv_phi3_HB.
    always @(posedge clk_180MHz or negedge rst_n) begin
        if (!rst_n) begin
            S1 <= 1'b0; S2 <= 1'b0; S3 <= 1'b0;
            S4 <= 1'b0; S5 <= 1'b0; S6 <= 1'b0;
            tb_dt_a <= 12'd0; tb_dt_b <= 12'd0; tb_dt_c <= 12'd0;
            tb_pending_a <= 1'b0; tb_pending_b <= 1'b0; tb_pending_c <= 1'b0;
        end else begin
            if (tb_dt_a != 0) begin
                S1 <= 1'b0; S2 <= 1'b0;
                if (tb_dt_a == 1) begin
                    if (tb_pending_a) S1 <= 1'b1; else S2 <= 1'b1;
                    tb_dt_a <= 0;
                end else tb_dt_a <= tb_dt_a - 1'b1;
            end else if (tb_raw_a && !S1) begin
                S1 <= 1'b0; S2 <= 1'b0; tb_pending_a <= 1'b1;
                tb_dt_a <= TB_DEADTIME - 1;
            end else if (!tb_raw_a && !S2) begin
                S1 <= 1'b0; S2 <= 1'b0; tb_pending_a <= 1'b0;
                tb_dt_a <= TB_DEADTIME - 1;
            end

            if (tb_dt_b != 0) begin
                S3 <= 1'b0; S4 <= 1'b0;
                if (tb_dt_b == 1) begin
                    if (tb_pending_b) S3 <= 1'b1; else S4 <= 1'b1;
                    tb_dt_b <= 0;
                end else tb_dt_b <= tb_dt_b - 1'b1;
            end else if (tb_raw_b && !S3) begin
                S3 <= 1'b0; S4 <= 1'b0; tb_pending_b <= 1'b1;
                tb_dt_b <= TB_DEADTIME - 1;
            end else if (!tb_raw_b && !S4) begin
                S3 <= 1'b0; S4 <= 1'b0; tb_pending_b <= 1'b0;
                tb_dt_b <= TB_DEADTIME - 1;
            end

            if (tb_dt_c != 0) begin
                S5 <= 1'b0; S6 <= 1'b0;
                if (tb_dt_c == 1) begin
                    if (tb_pending_c) S5 <= 1'b1; else S6 <= 1'b1;
                    tb_dt_c <= 0;
                end else tb_dt_c <= tb_dt_c - 1'b1;
            end else if (tb_raw_c && !S5) begin
                S5 <= 1'b0; S6 <= 1'b0; tb_pending_c <= 1'b1;
                tb_dt_c <= TB_DEADTIME - 1;
            end else if (!tb_raw_c && !S6) begin
                S5 <= 1'b0; S6 <= 1'b0; tb_pending_c <= 1'b0;
                tb_dt_c <= TB_DEADTIME - 1;
            end
        end
    end
    
    // Inductor Module Positive Inputs (Driven by Inverter Module)
    wire signed [34:0] UAO_P_S35, UBO_P_S35, UCO_P_S35;
    
    // Inductor Module Parameters
    reg [15:0] I_OV_20LinuH_Q18;
    reg [15:0] Res_S16_Q12;
    
    // Dynamic Neutral Point Voltage Feedback Wires
    wire signed [34:0] U_N_S35_Q17;
    wire signed [34:0] UAO_N_S35 = U_N_S35_Q17;   
    wire signed [34:0] UBO_N_S35 = U_N_S35_Q17;
    wire signed [34:0] UCO_N_S35 = U_N_S35_Q17;

    // Inductor Module Outputs
    wire signed [34:0] x_1, x_2, x_3;
    wire [15:0] Curt1_L15, Curt1_H15;
    wire [15:0] Curt2_L15, Curt2_H15;
    wire [15:0] Curt3_L15, Curt3_H15;
    
    // Inverter Current Feedback (Convert Inductor S35_Q25 output to S35_Q17 for Inverter)
    wire signed [34:0] Ia_inv_S35_Q17 = x_1 >>> 8;
    wire signed [34:0] Ib_inv_S35_Q17 = x_2 >>> 8;
    wire signed [34:0] Ic_inv_S35_Q17 = x_3 >>> 8;
    
    // Clarke Module Outputs
    wire signed [17:0] I_alpha_S18_Q9;
    wire signed [17:0] I_beta_S18_Q9;
    
    // Park Module Outputs
    wire signed [17:0] I_d_S18_Q9;
    wire signed [17:0] I_q_S18_Q9;

    // Torque Calculation Module & Shared Magnetic Parameters
    reg  signed [15:0] Ld_dash_Lq_S16_Q12;
    reg  signed [15:0] p_n_S16_Q0;
    reg  signed [15:0] Phir_Half_S16_Q15; 
    wire signed [34:0] Torque_Out_S35_Q17; 

    // Mechanical Module Inputs & Outputs
    reg  signed [15:0] Freq_Division_S16;
    reg  signed [15:0] TsOverJ_S16_Q27;
    reg  signed [15:0] TsOver2pi_S16_Q34;
    reg  signed [15:0] B_S16_Q11;
    
    // Load Torque Variables & Format Conversion
    reg  signed [15:0] TL_S16_Q5;         

    wire signed [17:0] OMGm_S18_Q4;
    wire signed [17:0] ePOS_S18_360_out; 
    wire signed [17:0] eOMG_S18_Q4_wire;
    
    // BackEMF Module Inputs & Outputs
    reg  signed [15:0] Delta_S16_360;
    wire signed [34:0] eA_S35_Q17;
    wire signed [34:0] eB_S35_Q17;
    wire signed [34:0] eC_S35_Q17;

    // add3over3 and Volt_N_calc Interconnects
    wire signed [34:0] U1_S35_Q17, U2_S35_Q17, U3_S35_Q17;

    // =========================================================================
    // Instantiate UUT0: Physical 3-Phase Half-Bridge Inverter
    // =========================================================================
    inv_phi3_HB uut_inverter (
        .clk_180MHz   (clk_180MHz),
        .rst_n        (rst_n),
        .S1           (S1),
        .S2           (S2),
        .S3           (S3),
        .S4           (S4),
        .S5           (S5),
        .S6           (S6),
        .Ia_S35_Q17   (Ia_inv_S35_Q17),  // Current feedback for deadtime/diode logic
        .Ib_S35_Q17   (Ib_inv_S35_Q17),
        .Ic_S35_Q17   (Ic_inv_S35_Q17),
        // DC Bus configuration. 366 in Q5 shifted internally by 11 bits ≈ 749568. 
        // 749568 - (-749568) = 1499136 (approx 1500000 threshold previously used)
        .Udc1P_S16_Q5 (16'sd3200), 
        .Udc2P_S16_Q5 (16'sd3200),
        .Udc3P_S16_Q5 (16'sd3200),
        .Udc1N_S16_Q5 (-16'sd3200),
        .Udc2N_S16_Q5 (-16'sd3200),
        .Udc3N_S16_Q5 (-16'sd3200),
        .Rd_S16_Q15   (16'sd0),          // Ideal switch resistance for baseline sim
        .Vd_S16_Q15   (16'sd0),          // Ideal diode voltage drop for baseline sim
        .x_1          (UAO_P_S35),       // Phase A voltage output
        .x_2          (UBO_P_S35),       // Phase B voltage output
        .x_3          (UCO_P_S35),       // Phase C voltage output
        .x_4          (),                // Lower switch current monitoring bypassed
        .x_5          (),
        .x_6          (),
        .x_7          (),
        .x_8          (),
        .x_9          (),
        .x_10         ()
    );

    // =========================================================================
    // Instantiate UUT1: Inductor Model
    // =========================================================================
    Inductor uut_inductor (
        .clk_180MHz(clk_180MHz),
        .UAO_P_S35(UAO_P_S35), .UBO_P_S35(UBO_P_S35), .UCO_P_S35(UCO_P_S35),
        .UAO_N_S35(UAO_N_S35), .UBO_N_S35(UBO_N_S35), .UCO_N_S35(UCO_N_S35), 
        .bEMF_A_S35_Q17(eA_S35_Q17), .bEMF_B_S35_Q17(eB_S35_Q17),
        .bEMF_C_S35_Q17(eC_S35_Q17),
        .I_OV_20LinuH_Q18(I_OV_20LinuH_Q18),
        .Res_S16_Q12(Res_S16_Q12),
        .rst_n(rst_n),
        .x_1(x_1), .x_2(x_2), .x_3(x_3),
        .Curt1_L15(Curt1_L15), .Curt1_H15(Curt1_H15),
        .Curt2_L15(Curt2_L15), .Curt2_H15(Curt2_H15),
        .Curt3_L15(Curt3_L15), .Curt3_H15(Curt3_H15)
    );

    // =========================================================================
    // Instantiate UUT2: Clarke Transform
    // =========================================================================
    Clarke3Phase uut_clarke (
        .clk_180MHz      (clk_180MHz),
        .rst_n           (rst_n),
        .I_A_S35_Q25     (x_1),
        .I_B_S35_Q25     (x_2),
        .I_C_S35_Q25     (x_3),
        .I_alpha_S18_Q9  (I_alpha_S18_Q9),
        .I_beta_S18_Q9   (I_beta_S18_Q9)
    );

    // =========================================================================
    // Instantiate UUT3: Park Transform
    // =========================================================================
    Park2dq uut_park (
        .clk_180MHz      (clk_180MHz),
        .rst_n           (rst_n),
        .epos_S18        (ePOS_S18_360_out), 
        .I_alpha_S18_Q9  (I_alpha_S18_Q9),
        .I_beta_S18_Q9   (I_beta_S18_Q9),  
        .I_d_S18_Q9      (I_d_S18_Q9),
        .I_q_S18_Q9      (I_q_S18_Q9)
    );

    // =========================================================================
    // Instantiate UUT4: Torque Calculation
    // =========================================================================
    Te_calc uut_te_calc (
        .clk_180MHz         (clk_180MHz),
        .rst_n              (rst_n),
        .I_d_S18_Q9         (I_d_S18_Q9),
        .I_q_S18_Q9         (I_q_S18_Q9),
        .Ld_dash_Lq_S16_Q12 (Ld_dash_Lq_S16_Q12), 
        .Phir_Half_S16_Q15  (Phir_Half_S16_Q15),      
        .p_n_S16_Q0         (p_n_S16_Q0),        
        .Torque_Out_S35_Q17 (Torque_Out_S35_Q17)
    );

    // =========================================================================
    // Instantiate UUT5: Mechanical Model
    // =========================================================================
    Mechanical uut_mechanical (
        .clk_180MHz         (clk_180MHz),
        .rst_n              (rst_n),
        .Freq_Division_S16  (Freq_Division_S16),
        .TsOverJ_S16_Q27    (TsOverJ_S16_Q27),
        .TsOver2pi_S16_Q34  (TsOver2pi_S16_Q34),
        .Te_S35_Q17         (Torque_Out_S35_Q17), 
        .TL_S16_Q5          (TL_S16_Q5),         
        .B_S16_Q11          (B_S16_Q11),
        .p_n_S16_Q0         (p_n_S16_Q0),         
        .OMGm_S18_Q4        (OMGm_S18_Q4),
        .ePOS_S18_360       (ePOS_S18_360_out),
        .eOMG_S18_Q4        (eOMG_S18_Q4_wire)
    );

    // =========================================================================
    // Instantiate UUT6: BackEMF Calculation
    // =========================================================================
    BackEMF uut_backemf (
        .clk                (clk_180MHz),
        .rst_n              (rst_n),
        .epos_S18_360       (ePOS_S18_360_out),  
        .Delta_S16_360      (Delta_S16_360),
        .eOMG_S18_Q4        (eOMG_S18_Q4_wire), 
        .Phir_Half_S16_Q15  (Phir_Half_S16_Q15), 
        .eA_S35_Q17         (eA_S35_Q17),        
        .eB_S35_Q17         (eB_S35_Q17),        
        .eC_S35_Q17         (eC_S35_Q17),        
        .eA_STM32_S16         (),                  
        .eD_S35_Q17         (),                  
        .eE_S35_Q17         (),
        .eF_S35_Q17         ()
    );

    // =========================================================================
    // Instantiate UUT7: Average Voltage Calculation (add3over3)
    // =========================================================================
    add3over3 uut_add3over3 (
        .clk_fast    (clk_180MHz),
        .rst_n       (rst_n),
        .Ua1_S35_Q17 (UAO_P_S35),     
        .Ub1_S35_Q17 (UBO_P_S35),     
        .Uc1_S35_Q17 (UCO_P_S35),     
        .Ua2_S35_Q17 (eA_S35_Q17),    
        .Ub2_S35_Q17 (eB_S35_Q17),    
        .Uc2_S35_Q17 (eC_S35_Q17),    
        .Ua3_S35_Q17 (35'sd0),        
        .Ub3_S35_Q17 (35'sd0),
        .Uc3_S35_Q17 (35'sd0),
        .U1_S35_Q17  (U1_S35_Q17),    
        .U2_S35_Q17  (U2_S35_Q17),    
        .U3_S35_Q17  (U3_S35_Q17)     
    );

    // =========================================================================
    // Instantiate UUT8: Neutral Point Voltage Calculation
    // =========================================================================
    Volt_N_calc uut_volt_n_calc (
        .clk              (clk_180MHz),
        .rst_n            (rst_n),
        .sum_uX0_ovr3     (U1_S35_Q17), 
        .sum_eX_ovr3      (U2_S35_Q17),
        .sum_eMUTUAL_ovr3 (U3_S35_Q17),
        .U_N_STM32          (),
        .U_N_S35_Q17      (U_N_S35_Q17) 
    );
    
    // Generate 180MHz Clock
    initial begin
        clk_180MHz = 0;
        forever #2.777 clk_180MHz = ~clk_180MHz;
    end
    
    // Initialize LUT and static parameters
    initial begin
        rst_n = 0;

        // --- Inductor Model Setup ---
        I_OV_20LinuH_Q18 = 16'd4; 
        Res_S16_Q12 = 16'd4096;

        // --- Torque Calculation Setup ---
        p_n_S16_Q0 = 16'sd4;         
        Ld_dash_Lq_S16_Q12 = -16'sd12; 
        Phir_Half_S16_Q15 = 16'sd1638; 

        // --- Mechanical Model Setup ---
        Freq_Division_S16 = 16'sd1;      
        TsOverJ_S16_Q27 = 16'sd26844;    
        TsOver2pi_S16_Q34 = 16'sd27342;  
        TL_S16_Q5 = 16'sd0;              
        B_S16_Q11 = 16'sd2;              

        // --- BackEMF Model Setup ---
        Delta_S16_360 = 16'sd10923; 
        
        #150;
        rst_n = 1;
        
        // Dynamic Load Testing Sequence
        #2000000;
        TL_S16_Q5 = 16'sd16;  
        
        #4000000; 
        TL_S16_Q5 = 16'sd32;   //1.0 N*m
        
        #20000000; 
        
        $stop;
    end
    
endmodule
